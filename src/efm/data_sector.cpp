// ECMA-130 14.1: the Sync field is (00), ten times (FF), (00).
constexpr std::array<std::uint8_t, kSectorSyncBytes> kSectorSync = {
    0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00};

// ECMA-130 14.3: the EDC generator x^32 + x^31 + x^16 + x^15 + x^4 + x^3 + x
// + 1 in least-significant-bit-first (reflected) form.
constexpr std::uint32_t kEdcPolynomialReflected = 0xD8018001U;

// ECMA-130 Annex A: GF(2^8) is generated by P(x) = x^8 + x^4 + x^3 + x^2 + 1.
constexpr unsigned kGfPolynomial = 0x11DU;

// ECMA-130 Annex B: the scrambler is a 15-bit register fed back according to
// x^15 + x + 1 and preset to 0000 0000 0000 0001 after the Sync.
constexpr unsigned kScramblerRegisterBits = 15;
constexpr std::uint16_t kScramblerPreset = 0x0001U;

// ECMA-130 Annex A: the RSPC operates on the 2 236 bytes from byte 12, seen as
// 1 118 16-bit words split into an MSB and an LSB plane. The P code covers 43
// columns of 24 words (86 byte codewords of (26,24)), the Q code 26 diagonals
// of 43 words (52 byte codewords of (45,43)).
constexpr std::size_t kRspcBlockBytes = 2236;
constexpr std::size_t kPCodewords = 86;
constexpr std::size_t kPDataBytes = 24;
constexpr std::size_t kPStride = 86;
constexpr std::size_t kPMajorStride = 2;
constexpr std::size_t kQCodewords = 52;
constexpr std::size_t kQDataBytes = 43;
constexpr std::size_t kQStride = 88;
constexpr std::size_t kQMajorStride = 86;

constexpr std::size_t kSectionsPerSecond = kSubcodeSectionsPerSecond;
constexpr std::size_t kSectionsPerMinute = 60 * kSectionsPerSecond;

struct GfTables {
  // forward[a] = a * x; backward[a ^ forward[a]] = a, i.e. division by (x + 1).
  std::array<std::uint8_t, 256> forward{};
  std::array<std::uint8_t, 256> backward{};
  std::array<std::uint32_t, 256> edc{};
};

GfTables MakeTables() {
  GfTables tables;
  for (unsigned i = 0; i < 256U; ++i) {
    const unsigned doubled =
        (i << 1U) ^ ((i & 0x80U) != 0U ? kGfPolynomial : 0U);
    tables.forward[i] = static_cast<std::uint8_t>(doubled);
    tables.backward[i ^ doubled] = static_cast<std::uint8_t>(i);
    std::uint32_t edc = i;
    for (int bit = 0; bit < 8; ++bit) {
      edc = (edc >> 1U) ^ ((edc & 1U) != 0U ? kEdcPolynomialReflected : 0U);
    }
    tables.edc[i] = edc;
  }
  return tables;
}

const GfTables& Tables() {
  static const GfTables tables = MakeTables();
  return tables;
}

std::array<std::uint8_t, kSectorBytes> MakeScrambleTable() {
  std::array<std::uint8_t, kSectorBytes> table{};
  std::uint16_t reg = kScramblerPreset;
  for (std::size_t index = kSectorSyncBytes; index < kSectorBytes; ++index) {
    std::uint8_t value = 0;
    // The least significant bit of each byte comes first.
    for (unsigned bit = 0; bit < 8U; ++bit) {
      value = static_cast<std::uint8_t>(value | ((reg & 1U) << bit));
      const unsigned feedback = (reg ^ (reg >> 1U)) & 1U;
      reg = static_cast<std::uint16_t>(
          (reg >> 1U) | (feedback << (kScramblerRegisterBits - 1U)));
    }
    table[index] = value;
  }
  return table;
}

std::uint8_t ToBcd(std::size_t value) {
  return static_cast<std::uint8_t>(((value / 10) << 4U) | (value % 10));
}

// ECMA-130 14.2: MIN, SEC and FRAC of a Sector Address, each two BCD digits.
void WriteHeader(std::size_t address, std::uint8_t minute_offset,
                 std::uint8_t mode, Sector* sector) {
  address = std::min(address, kMaxSectorAddress);
  const std::size_t minutes = address / kSectionsPerMinute;
  const std::size_t seconds =
      (address % kSectionsPerMinute) / kSectionsPerSecond;
  const std::size_t frames = address % kSectionsPerSecond;
  (*sector)[kSectorHeaderOffset] =
      static_cast<std::uint8_t>(ToBcd(minutes) + minute_offset);
  (*sector)[kSectorHeaderOffset + 1] = ToBcd(seconds);
  (*sector)[kSectorHeaderOffset + 2] = ToBcd(frames);
  (*sector)[kSectorModeOffset] = mode;
}

// Encodes `major_count` Reed-Solomon codewords of `minor_count` data bytes
// with two parity bytes each, the scheme of ECMA-130 Annex A for both the P
// and the Q code. Codeword `major` starts at byte (major / 2) * major_stride +
// (major % 2) of `block` and steps by `minor_stride` bytes, wrapping modulo
// the block size; its two parity bytes are written to parity[major] and
// parity[major + major_count].
void ComputeParity(const std::uint8_t* block, std::size_t major_count,
                   std::size_t minor_count, std::size_t major_stride,
                   std::size_t minor_stride, std::uint8_t* parity) {
  const GfTables& tables = Tables();
  const std::size_t size = major_count * minor_count;
  for (std::size_t major = 0; major < major_count; ++major) {
    std::size_t index = (major >> 1U) * major_stride + (major & 1U);
    std::uint8_t weighted = 0;
    std::uint8_t sum = 0;
    for (std::size_t minor = 0; minor < minor_count; ++minor) {
      const std::uint8_t value = block[index];
      index += minor_stride;
      if (index >= size) {
        index -= size;
      }
      weighted = static_cast<std::uint8_t>(weighted ^ value);
      sum = static_cast<std::uint8_t>(sum ^ value);
      weighted = tables.forward[weighted];
    }
    // Solves for the two parity bytes that zero both syndromes.
    weighted = tables.backward[tables.forward[weighted] ^ sum];
    parity[major] = weighted;
    parity[major + major_count] = static_cast<std::uint8_t>(weighted ^ sum);
  }
}

void FinishMode1Sector(Sector* sector) {
  const std::uint32_t edc = ComputeEdc(sector->data(), kSectorEdcOffset);
  // ECMA-130 14.3: the EDC is recorded least significant byte first.
  for (std::size_t byte = 0; byte < 4; ++byte) {
    (*sector)[kSectorEdcOffset + byte] =
        static_cast<std::uint8_t>((edc >> (8U * byte)) & 0xFFU);
  }
  WriteRspcParity(sector);
}

