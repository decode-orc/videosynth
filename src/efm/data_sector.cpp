std::uint8_t ScrambleByte(std::size_t index) {
  static const std::array<std::uint8_t, kSectorBytes> table =
      MakeScrambleTable();
  return index < kSectorBytes ? table[index] : 0;
}

std::uint32_t ComputeEdc(const std::uint8_t* bytes, std::size_t count) {
  const GfTables& tables = Tables();
  std::uint32_t edc = 0;
  for (std::size_t index = 0; index < count; ++index) {
    edc = (edc >> 8U) ^ tables.edc[(edc ^ bytes[index]) & 0xFFU];
  }
  return edc;
}

void WriteRspcParity(Sector* sector) {
  static_assert(kSectorHeaderOffset + kRspcBlockBytes == kSectorQParityOffset);
  static_assert(kPCodewords * kPDataBytes ==
                kSectorPParityOffset - kSectorHeaderOffset);
  static_assert(kQCodewords * kQDataBytes == kRspcBlockBytes);
  std::uint8_t* block = sector->data() + kSectorHeaderOffset;
  ComputeParity(block, kPCodewords, kPDataBytes, kPMajorStride, kPStride,
                sector->data() + kSectorPParityOffset);
  ComputeParity(block, kQCodewords, kQDataBytes, kQMajorStride, kQStride,
                sector->data() + kSectorQParityOffset);
}

void ScrambleSector(Sector* sector) {
  for (std::size_t index = kSectorSyncBytes; index < kSectorBytes; ++index) {
    (*sector)[index] =
        static_cast<std::uint8_t>((*sector)[index] ^ ScrambleByte(index));
  }
}

Sector BuildMode1Sector(
    std::size_t address,
    const std::array<std::uint8_t, kMode1UserDataBytes>& user_data) {
  Sector sector{};
  std::copy(kSectorSync.begin(), kSectorSync.end(), sector.begin());
  WriteHeader(address, 0, kSectorMode1, &sector);
  std::copy(user_data.begin(), user_data.end(),
            sector.begin() + kSectorUserDataOffset);
  FinishMode1Sector(&sector);
  return sector;
}

Sector BuildLeadInMode1Sector(std::size_t relative_address) {
  Sector sector{};
  std::copy(kSectorSync.begin(), kSectorSync.end(), sector.begin());
  WriteHeader(relative_address, kLeadInSectorMinuteOffset, kSectorMode1,
              &sector);
  FinishMode1Sector(&sector);
  return sector;
}

Sector BuildMode0Sector(std::size_t address) {
  Sector sector{};
  std::copy(kSectorSync.begin(), kSectorSync.end(), sector.begin());
  WriteHeader(address, 0, kSectorMode0, &sector);
  return sector;
}

std::array<F1Frame, kFramesPerSubcodeSection> SectorToF1Frames(
    const Sector& scrambled_sector) {
  std::array<F1Frame, kFramesPerSubcodeSection> frames{};
  for (std::size_t frame = 0; frame < kFramesPerSubcodeSection; ++frame) {
    const std::size_t base = frame * kF1FrameBytes;
    for (std::size_t byte = 0; byte < kF1FrameBytes; byte += 2) {
      frames[frame][byte] = scrambled_sector[base + byte + 1];
      frames[frame][byte + 1] = scrambled_sector[base + byte];
    }
  }
  return frames;
}

